// Embeds the Go templates into a TypeScript module, so the adapter can write them into the
// work directory without reading from disk at runtime — it is bundled into the Electron
// main process, where the package directory no longer exists (ADR 0005).
//
// The templates are real `.go` files: the Go compiler checks them, `go vet` runs on them
// and an editor highlights them. This script only moves them across the language border.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const templates = join(here, '..', 'templates')
const target = join(here, '..', 'src', 'templates.generated.ts')

const harness = readFileSync(join(templates, 'Harness.java'), 'utf8')
const json = readFileSync(join(templates, 'Json.java'), 'utf8')

writeFileSync(
  target,
  `// GENERATED by scripts/embed-templates.mjs from templates/*.java.
// Do not edit by hand: generated files are never edited by hand (ADR 0005).

export const harnessTemplate = ${JSON.stringify(harness)}

export const jsonTemplate = ${JSON.stringify(json)}
`,
  'utf8',
)

console.log(`embedded ${harness.length + json.length} bytes into ${target}`)
