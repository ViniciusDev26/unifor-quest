// Embeds the Elixir templates into a TypeScript module, so the adapter can write them into
// the work directory without reading from disk at runtime — it is bundled into the Electron
// main process, where the package directory no longer exists (ADR 0005).
//
// The templates are real `.ex`/`.exs` files, runnable and checkable by Elixir itself. This
// script only moves them across the language border.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

// Git checks these out with CRLF on Windows, and the embedded copy would differ from the
// one generated anywhere else — enough to make the committed file impossible to keep in
// sync across platforms. The generator decides the line ending, not the checkout.
const read = (path) => readFileSync(path, 'utf8').replaceAll('\r\n', '\n')

const here = dirname(fileURLToPath(import.meta.url))
const templates = join(here, '..', 'templates')
const target = join(here, '..', 'src', 'templates.generated.ts')

const harness = read(join(templates, 'harness.exs'))
const prelude = read(join(templates, 'graph.ex'))

writeFileSync(
  target,
  `// GENERATED by scripts/embed-templates.mjs from templates/*.ex(s).
// Do not edit by hand: generated files are never edited by hand (ADR 0005).

export const harnessTemplate = ${JSON.stringify(harness)}

export const preludeSource = ${JSON.stringify(prelude)}
`,
  'utf8',
)

console.log(`embedded ${harness.length + prelude.length} bytes into ${target}`)
